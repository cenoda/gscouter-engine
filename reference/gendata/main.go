// Command gendata writes engine/src/data.rs from gcsim's catalog: the
// names gcsl accepts for characters, weapons and sets, and the base stat
// data (curves and ascension stats) of the characters and weapons the
// engine implements.
//
// Usage: go run ./gendata > ../engine/src/data.rs
package main

import (
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/genshinsim/gcsim/pkg/catalog"
	"github.com/genshinsim/gcsim/pkg/core/info"
	"github.com/genshinsim/gcsim/pkg/core/keys"
	"github.com/genshinsim/gcsim/pkg/model"
	"github.com/genshinsim/gcsim/pkg/shortcut"
)

// implemented by the engine
var (
	chars   = []keys.Char{keys.HuTao, keys.Xingqiu, keys.Zhongli, keys.Yelan}
	weapons = []keys.Weapon{keys.StaffOfHoma, keys.SacrificialSword, keys.AquaSimulacra}
)

// fl prints a float as a Rust f64 literal, with the shortest digits that
// read back as the same value.
func fl(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

func main() {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("// Generated by reference/gendata from gcsim's catalog; do not edit.\n\n")
	w("#![allow(clippy::all)]\n\n")

	names := func(title string, m map[string]int) {
		w("pub static %s: &[(&str, u16)] = &[\n", title)
		for _, k := range slices.Sorted(maps.Keys(m)) {
			w("    (%q, %d),\n", k, m[k])
		}
		w("];\n\n")
	}
	cm := map[string]int{}
	for k, v := range shortcut.CharNameToKey {
		cm[k] = int(v)
	}
	names("CHAR_NAMES", cm)
	wm := map[string]int{}
	for k, v := range shortcut.WeaponNameToKey {
		wm[k] = int(v)
	}
	names("WEAPON_NAMES", wm)
	sm := map[string]int{}
	for k, v := range shortcut.SetNameToKey {
		sm[k] = int(v)
	}
	names("SET_NAMES", sm)

	key := func(title string, m map[string]int, str func(int) string) {
		// canonical key name by id
		ids := map[int]bool{}
		for _, v := range m {
			ids[v] = true
		}
		w("pub static %s: &[(u16, &str)] = &[\n", title)
		for _, id := range slices.Sorted(maps.Keys(ids)) {
			w("    (%d, %q),\n", id, str(id))
		}
		w("];\n\n")
	}
	key("CHAR_KEYS", cm, func(i int) string { return keys.Char(i).String() })
	key("WEAPON_KEYS", wm, func(i int) string { return keys.Weapon(i).String() })
	key("SET_KEYS", sm, func(i int) string { return keys.Set(i).String() })

	curves := map[model.GrowCurveType]bool{}
	promo := func(p []*model.PromotionData) string {
		var s []string
		for _, v := range p {
			var props []string
			for _, a := range v.AddProps {
				props = append(props, fmt.Sprintf("(%d, %s)", info.ConvertProtoStat(a.PropType), fl(a.Value)))
			}
			s = append(s, fmt.Sprintf("(%d, &[%s])", v.MaxLevel, strings.Join(props, ", ")))
		}
		return "&[" + strings.Join(s, ", ") + "]"
	}

	w("pub struct CharData {\n    pub key: &'static str,\n    pub base: [f64; 3],\n    pub curves: [u32; 3],\n    pub em: f64,\n    pub promo: &'static [(u32, &'static [(usize, f64)])],\n}\n\n")
	w("pub static CHARS: &[CharData] = &[\n")
	for _, k := range chars {
		d := catalog.CharacterMap[k].Stats
		curves[d.HpCurve], curves[d.AtkCurve], curves[d.DefCruve] = true, true, true
		w("    CharData { key: %q, base: [%s, %s, %s], curves: [%d, %d, %d], em: %s, promo: %s },\n",
			k.String(), fl(d.BaseHp), fl(d.BaseAtk), fl(d.BaseDef), d.HpCurve, d.AtkCurve, d.DefCruve, fl(d.ElementMastery), promo(d.PromoData))
	}
	w("];\n\n")

	w("pub struct WeaponData {\n    pub key: &'static str,\n    pub props: &'static [(usize, f64, u32)],\n    pub promo: &'static [(u32, &'static [(usize, f64)])],\n}\n\n")
	w("pub static WEAPONS: &[WeaponData] = &[\n")
	for _, k := range weapons {
		d := catalog.WeaponMap[k].BaseStats
		var props []string
		for _, p := range d.BaseProps {
			curves[p.Curve] = true
			props = append(props, fmt.Sprintf("(%d, %s, %d)", info.ConvertProtoStat(p.PropType), fl(p.InitialValue), p.Curve))
		}
		w("    WeaponData { key: %q, props: &[%s], promo: %s },\n", k.String(), strings.Join(props, ", "), promo(d.PromoData))
	}
	w("];\n\n")

	w("pub static CURVES: &[(u32, &[f64])] = &[\n")
	for _, c := range slices.Sorted(maps.Keys(curves)) {
		var vs []string
		for _, v := range catalog.GrowCurve[c] {
			vs = append(vs, fl(v))
		}
		w("    (%d, &[%s]),\n", c, strings.Join(vs, ", "))
	}
	w("];\n")
	fmt.Print(b.String())
}
