//! `gsc`: checks content records and converts them to the engine's data.
//!
//!     gsc check <record.toml>...
//!     gsc convert <record.toml> [--select legacy|independent] [--out <dir>]
//!     gsc status <record.toml>...
//!     gsc import <character>          (a draft record from legacy data)
//!
//! Run from anywhere inside the repository. `convert` writes
//! `<dir>/<module>.rs` (the tables module) and `<dir>/<module>.row.rs` (the
//! CHARS row for `engine/src/data.rs`); without `--out` it prints both.

use gse_content::{catalog::Catalog, convert, record::Select, validate};
use std::path::Path;
use std::process::ExitCode;

fn fail(errs: &[String]) -> ExitCode {
    for e in errs {
        eprintln!("{e}");
    }
    ExitCode::FAILURE
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let cat = match Catalog::find(Path::new(".")) {
        Ok(c) => c,
        Err(e) => return fail(&[e]),
    };
    let opt = |name: &str| args.iter().position(|a| a == name).and_then(|i| args.get(i + 1)).cloned();
    let files: Vec<&String> = args.iter().skip(1).enumerate().filter(|(i, a)| !a.starts_with("--") && (*i == 0 || !args[*i].starts_with("--"))).map(|(_, a)| a).collect();
    match args.first().map(String::as_str) {
        Some("check") => {
            let mut errs = Vec::new();
            for f in &files {
                match gse_content::load(Path::new(f), &cat) {
                    Ok(r) => println!("{}: valid, {} values, {} sources", r.path, r.values.len(), r.sources.len()),
                    Err(e) => errs.extend(e),
                }
            }
            if errs.is_empty() { ExitCode::SUCCESS } else { fail(&errs) }
        }
        Some("status") => {
            for f in &files {
                let r = match gse_content::load(Path::new(f), &cat) {
                    Ok(r) => r,
                    Err(e) => return fail(&e),
                };
                let s = match validate::status(&r) {
                    Ok(s) => s,
                    Err(e) => return fail(&e),
                };
                println!("{}: {} as new content (selection independent)", r.path, s.status);
                for (what, list) in [("high uncertainty", &s.high), ("legacy only", &s.legacy_fallback), ("estimated or stated", &s.estimated), ("unresolved", &s.unresolved)] {
                    if !list.is_empty() {
                        println!("  {what} ({}):", list.len());
                        for x in list {
                            println!("    {x}");
                        }
                    }
                }
            }
            ExitCode::SUCCESS
        }
        Some("convert") => {
            let Some(f) = files.first() else { return fail(&["gsc convert <record.toml>".into()]) };
            let r = match gse_content::load(Path::new(f), &cat) {
                Ok(r) => r,
                Err(e) => return fail(&e),
            };
            let sel = match opt("--select") {
                None => r.select,
                Some(s) => match Select::parse(&s) {
                    Some(x) => x,
                    None => return fail(&[format!("--select {s}: legacy or independent")]),
                },
            };
            let out = match convert::convert(&r, sel) {
                Ok(o) => o,
                Err(e) => return fail(&e),
            };
            let module = convert::module_text(&r, sel, &out.items);
            let row = out.row.as_ref().map(convert::row_text).unwrap_or_default();
            match opt("--out") {
                Some(dir) => {
                    let d = Path::new(&dir);
                    let w = |name: String, text: &str| std::fs::write(d.join(&name), text).map_err(|e| format!("{name}: {e}"));
                    let row_file = format!("// Generated by gsc convert (content/) from {} (selection: {}); do not edit.\n// The row of engine/src/data.rs CHARS.\n{row}\n", r.path, sel.name());
                    if let Err(e) = std::fs::create_dir_all(d).map_err(|e| e.to_string()).and_then(|_| w(format!("{}.rs", r.module), &module)).and_then(|_| w(format!("{}.row.rs", r.module), &row_file)) {
                        return fail(&[e]);
                    }
                    eprintln!("wrote {dir}/{0}.rs and {dir}/{0}.row.rs", r.module);
                }
                None => println!("{module}\n{row}"),
            }
            ExitCode::SUCCESS
        }
        Some("import") => {
            let Some(k) = files.first() else { return fail(&["gsc import <character>".into()]) };
            match gse_content::import::import(&cat, k) {
                Ok(t) => {
                    print!("{t}");
                    ExitCode::SUCCESS
                }
                Err(e) => fail(&[e]),
            }
        }
        _ => fail(&["usage: gsc check|status <record.toml>... | gsc convert <record.toml> [--select legacy|independent] [--out <dir>] | gsc import <character>".into()]),
    }
}
