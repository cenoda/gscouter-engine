//! The proof of step 1's input format on Xiangling (docs/content-format.md
//! §7): her record converts back to her current engine data exactly under
//! the legacy selection, and differs from it only within each observation's
//! stated precision under the independent selection. Every character's
//! legacy data also round-trips through `gsc import` and `gsc convert`.

use gse_content::catalog::{self, Catalog};
use gse_content::convert::{self, resolve};
use gse_content::record::{self, Evidence, Select};
use gse_content::rustdata::{self, strip_header};
use gse_content::toml::Value;
use gse_content::validate;
use std::path::Path;

fn cat() -> Catalog {
    Catalog::find(Path::new(env!("CARGO_MANIFEST_DIR"))).unwrap()
}

fn record_path() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("records/chars/xiangling.toml")
}

fn xiangling(cat: &Catalog) -> record::Record {
    gse_content::load(&record_path(), cat).unwrap_or_else(|e| panic!("{}", e.join("\n")))
}

#[test]
fn legacy_selection_reproduces_the_engine_data_exactly() {
    let cat = cat();
    let r = xiangling(&cat);
    assert_eq!(r.select, Select::Legacy);
    let out = convert::convert(&r, Select::Legacy).unwrap();
    // the tables module, to the byte after its header
    let engine = catalog::read(&cat.char_module_path("xiangling")).unwrap();
    let ours = convert::module_text(&r, Select::Legacy, &out.items);
    assert_eq!(strip_header(&ours), strip_header(&engine));
    assert!(ours.starts_with("// Generated by gsc convert (content/) from content/records/chars/xiangling.toml"));
    // the CHARS row, to the byte
    let row = convert::row_text(out.row.as_ref().unwrap());
    let data = catalog::read(&cat.src.join("data.rs")).unwrap();
    assert!(data.lines().any(|l| l == row), "{row}");
}

#[test]
fn independent_selection_differs_only_within_stated_precision() {
    let cat = cat();
    let r = xiangling(&cat);
    let legacy = convert::convert(&r, Select::Legacy).unwrap();
    let indep = convert::convert(&r, Select::Independent).unwrap();
    assert_ne!(rustdata::module_body(&legacy.items), rustdata::module_body(&indep.items), "the official values must show");
    let (mut differ, mut same) = (0, 0);
    for v in r.values.iter().filter(|v| v.target.is_some()) {
        let a = resolve(v, Select::Legacy).unwrap();
        let b = resolve(v, Select::Independent).unwrap();
        let (mut xa, mut xb) = (Vec::new(), Vec::new());
        convert::leaves(&a.value, &mut |x| xa.extend(x.as_f64()));
        convert::leaves(&b.value, &mut |x| xb.extend(x.as_f64()));
        assert_eq!(xa.len(), xb.len(), "{}", v.key);
        for (k, (x, y)) in xa.iter().zip(&xb).enumerate() {
            // the observation the independent selection took for this leaf
            let c = if v.by.is_some() { &b.choices[k] } else { &b.choices[0] };
            if x == y {
                same += 1;
                continue;
            }
            differ += 1;
            assert!(matches!(c.evidence, Evidence::OfficialRounded | Evidence::Measured), "{}: {x} -> {y} from {:?}", v.key, c.evidence);
            assert!((x - y).abs() <= c.tol * (1.0 + 1e-9) + 1e-12, "{}[{k}]: legacy {x}, {} {y} (±{})", v.key, c.evidence.name(), c.tol);
        }
    }
    // 208 talent values were read at Lv.1-11/13; some agree to every digit
    assert!(differ > 150, "{differ} values differ");
    assert!(same > differ, "{same} values are the same");
    // the talent multipliers that differ are display rounding: under half
    // the last digit the page shows (at most 0.5 percentage points)
    let v = r.value("attack[0][0]").unwrap();
    let b = resolve(v, Select::Independent).unwrap();
    assert_eq!(b.value.as_array().unwrap()[0], Value::Float(0.421));
    assert_eq!(b.choices[0].evidence, Evidence::OfficialRounded);
    assert_eq!(b.choices[11].evidence, Evidence::LegacyGcsim, "Lv.12 is not on the page");
}

#[test]
fn the_official_breakpoints_check_the_legacy_base_stats() {
    // `validate` checks them; here the numbers themselves
    let cat = cat();
    let (_, row) = &cat.char_rows["xiangling"];
    let at = |s, lv, ph| validate::base_stat(row, s, lv, ph, &cat).unwrap();
    assert!((at("base_hp", 90, 6) - 10874.915).abs() < 1e-3);
    assert!((at("base_atk", 80, 6) - 209.549).abs() < 1e-3);
    assert_eq!(at("em", 90, 6), 96.0);
}

#[test]
fn status_as_new_content() {
    let cat = cat();
    let s = validate::status(&xiangling(&cat)).unwrap();
    // docs/pilot-xiangling/hidden.md §3: built on standard estimates and
    // statements, Xiangling would be highly uncertain
    assert_eq!(s.status, "high_uncertainty");
    for k in ["burst.spin_icd_tag", "burst.spin_hits_per_rotation", "guoba.particles"] {
        assert!(s.high.iter().any(|h| h.starts_with(k)), "{k}");
    }
    // measured: not counted against her
    assert!(!s.high.iter().any(|h| h.starts_with("burst.spin_period")));
}

#[test]
fn every_character_round_trips_through_import_and_convert() {
    let cat = cat();
    let mut failed = Vec::new();
    let mut text_only = 0;
    for (key, (row_text, row)) in &cat.char_rows {
        let module = match row.field("module") {
            Some(rustdata::RVal::S(m)) => m.clone(),
            _ => panic!("{key}"),
        };
        let draft = gse_content::import::import(&cat, key).unwrap();
        let r = match record::parse(&format!("{key}.toml"), &draft) {
            Ok(r) => r,
            Err(e) => {
                failed.push(format!("{key}: {}", e.join("; ")));
                continue;
            }
        };
        let errs = validate::validate(&r, &cat);
        if !errs.is_empty() {
            failed.push(format!("{key}: {}", errs[..errs.len().min(3)].join("; ")));
            continue;
        }
        let out = convert::convert(&r, Select::Legacy).unwrap();
        let path = cat.char_module_path(&module);
        if !path.is_file() {
            // a traveler: its row only
            assert!(out.items.is_empty(), "{key}");
        } else {
            let (ours, theirs) = (convert::module_text(&r, Select::Legacy, &out.items), catalog::read(&path).unwrap());
            if strip_header(&ours) != strip_header(&theirs) {
                // gendata printed floats as Go does (`1e-07`; a tie in the
                // 17th digit broken to even): the same bits in other text
                text_only += 1;
                if rustdata::parse_module(&ours).unwrap() != rustdata::parse_module(&theirs).unwrap() {
                    failed.push(format!("{key}: tables differ"));
                }
            }
        }
        if convert::row_text(out.row.as_ref().unwrap()).trim().trim_end_matches(',') != row_text {
            failed.push(format!("{key}: row differs"));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n"));
    assert!(cat.char_rows.len() > 100);
    assert!(text_only <= 4, "{text_only} modules differ in float text");
}

/// The validator, on broken copies of the record.
#[test]
fn the_validator_names_what_is_wrong() {
    let cat = cat();
    let good = catalog::read(&record_path()).unwrap();
    let check = |from: &str, to: &str, want: &str| {
        assert!(good.contains(from), "{from}");
        let bad = good.replacen(from, to, 1);
        let errs = match record::parse("x.toml", &bad) {
            Ok(r) => validate::validate(&r, &cat),
            Err(e) => e,
        };
        assert!(errs.iter().any(|e| e.contains(want)), "{from} -> {to}: wanted `{want}`, got:\n{}", errs.join("\n"));
    };
    // provenance
    check("evidence = \"official_rounded\"\n  source = \"hoyowiki\"", "evidence = \"official_rounded\"", "`source` is required");
    check("source = \"hoyowiki\"", "source = \"nowhere\"", "is not in [source]");
    check("observed = \"2026-11-05\"\ngame_version = \"live", "game_version = \"live", "no observation date");
    check("evidence = \"estimated\"\n  source = \"standard\"\n  basis = \"standard: the normal attack tag\"", "evidence = \"estimated\"\n  source = \"standard\"", "gives its `basis`");
    check("evidence = \"measured\"\n  source = \"frames_sheet\"", "evidence = \"measured\"\n  source = \"hoyowiki\"", "measured evidence needs");
    check("evidence = \"official\"\n  source = \"hoyowiki\"", "evidence = \"official\"\n  source = \"legacy_logic\"", "legacy_gcsim evidence comes from a legacy_gcsim source");
    check("kind = \"sheet\"", "kind = \"video\"\nvideo = \"https://youtu.be/x\"", "needs `at` with its timestamp");
    // units, ranges, references
    check("unit = \"atk_frac\"", "unit = \"furlongs\"", "is not a unit");
    check("data = \"normal_attack\"", "data = \"no_such_tag\"", "ICD tags");
    check("data = [22, 32, 22]", "data = [22, 99, 22]", "curve of the engine's CURVES");
    check("data = 0.8\n", "data = 800.0\n", "unit m takes");
    check("data = 438", "data = 438.5", "integers");
    check("target = \"ATTACK[0][0]\"", "target = \"ATACK[0][0]\"", "is not in [items]");
    check("key = \"xiangling\"", "key = \"xianglingg\"", "not in the engine's key table");
    check("key = \"xiangling\"", "key = \"xl\"", "is an alias");
    // official and legacy disagree beyond display rounding
    check("shown = [\"42.1%\"", "shown = [\"42.3%\"", "outside official_rounded shown as 0.423");
    check("shown = [912,", "shown = [915,", "outside the shown 915");
    // coverage
    check("target = \"ATTACK[4][0]\"", "engine = \"nowhere\"", "ATTACK has 4 rows, and its `len` says 5");
    check("target = \"ATTACK[2][1]\"", "engine = \"nowhere\"", "ATTACK[2] has 1 entries, and its `len` says 2");
    check("target = \"ATTACK[1][0]\"", "engine = \"nowhere\"", "ATTACK[1] has no value");
    // a talent row must hold every level the engine's tables do
    check("data = [0.71036, 0.76818, 0.826, 0.9086, 0.96642, 1.0325, 1.12336, 1.21422, 1.30508, 1.4042, 1.517775, 1.651339, 1.784903, 1.918468, 2.064174]", "data = [0.71036, 0.76818, 0.826, 0.9086, 0.96642, 1.0325, 1.12336, 1.21422, 1.30508, 1.4042, 1.517775]", "levels 1 to 11 only under selection independent");
    check("target = \"char.zone\"", "check = true", "no value targets char.zone");
}
